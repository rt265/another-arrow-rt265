"""内置关卡数据。

每个关卡使用等宽的字符网格描述，每行的字符含义为：

- ``.``：空格子；
- ``^`` / ``v`` / ``<`` / ``>``：对应方向的箭头。

网格的行数、列数由字符串数量与单行长度决定，因此关卡尺寸可以不同。
"""

from __future__ import annotations

from typing import Final

Level = tuple[str, ...]

LEVELS: Final[tuple[Level, ...]] = (
    # 第 1 关：4x4，5 个箭头，用于熟悉点击与飞出规则。
    (
        ".^v.",
        "..<.",
        "...<",
        ">...",
    ),
    # 第 2 关：5x5，8 个箭头，出现行列上的相互阻挡。
    (
        "..>.v",
        "^....",
        "^.^..",
        "....<",
        ".^v..",
    ),
    # 第 3 关：6x6，14 个箭头，多个箭头共用同一行或同一列。
    # 注意 (4,0) 必须是向左的箭头：它一旦朝上就会和 (0,0) 互相瞄准，
    # 两者都无法飞出，整关将变成死局（见 tests/test_session.py 的通关测试）。
    (
        "v.>..^",
        ".....<",
        "..^^..",
        "..v<..",
        "<...^<",
        "v..<.>",
    ),
)
